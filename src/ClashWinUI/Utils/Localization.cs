    /// 字典项同时暴露为强类型属性，以便在 XAML 中使用编译期绑定 {x:Bind Loc.Key}，
    /// 既获得 x:Bind 的性能与编译期校验，又能在切换语言时通过 INotifyPropertyChanged 实时刷新。
